import array

# 1. Введення даних користувачем та перетворення їх на список цілих чисел
input_data = input("Введіть цілі числа, розділені пробілами: ")
numbers_list = [int(x) for x in input_data.split()]

# 2. Створення одновимірного масиву за допомогою бібліотеки array
# Символ 'i' означає тип даних signed int (цілі числа зі знаком)
arr = array.array('i', numbers_list)

# 3. Обчислення середнього арифметичного елементів масиву
if len(arr) > 0:
    average = sum(arr) / len(arr)
    print(f"Ваш масив: {arr.tolist()}")
    print(f"Середнє арифметичне елементів: {average:.2f}")
else:
    print("Масив порожній. Перезапустіть програму та введіть числа.")
