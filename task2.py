import numpy as np

# 1. Створення двовимірного масиву (матриці 3x3) з випадковими числами від 1 до 50
matrix = np.random.randint(1, 51, size=(3, 3))

print("Згенерований двовимірний масив (матриця 3x3):")
print(matrix)

# 2. Приклад обробки (знаходження середнього значення всіх елементів матриці)
matrix_average = np.mean(matrix)
print(f"\nСереднє арифметичне всіх елементів матриці: {matrix_average:.2f}")
